#!/usr/bin/env python3
"""Offline tests of blender/sky/build_sky_manifest.py (the living sky's 42 face textures for the keyed upload).

Everything runs in a temp folder (a fake game root + a fake .superpowers/sky-final with small generated 1024 px PNGs);
the real blender/textures/ is never touched and nothing is uploaded. Exit code 0 = all passed.

    py -3.12 tools/test_sky_manifest.py
"""
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "blender", "sky"))
import build_sky_manifest as M  # noqa: E402

THEMES = ["day_vivid", "dusk_amber", "night_aurora", "storm_teal", "lava_obsidian", "frost_glacial", "shadow_eclipse"]
FACES = ["Bk", "Dn", "Ft", "Lf", "Rt", "Up"]

# a two-key vortex index in build_vortex.py's format (indent 2, sorted keys)
VORTEX = {
    "comment": "GENERATED by blender/textures/build_vortex.py: Image assets for tools/upload_assets.py --textures",
    "keys": {
        "vortex_arms": {"contentHash": "a" * 64, "description": "Nimbus Climb gate vortex layer vortex_arms",
                        "displayName": "NC vortex arms", "png": "blender/textures/vortex/vortex_arms.png",
                        "structureHash": "2d61feb51a7c6bae74fcec251b494041"},
        "vortex_rim": {"contentHash": "b" * 64, "description": "Nimbus Climb gate vortex layer vortex_rim",
                       "displayName": "NC vortex rim", "png": "blender/textures/vortex/vortex_rim.png",
                       "structureHash": "2d61feb51a7c6bae74fcec251b494041"},
    },
}


def sha(path):
    with open(path, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def make_src(src, size=1024, themes=THEMES, skip=()):
    for ti, theme in enumerate(themes):
        os.makedirs(os.path.join(src, theme), exist_ok=True)
        for fi, face in enumerate(FACES):
            if (theme, face) in skip:
                continue
            Image.new("RGB", (size, size), (20 + ti * 30, 40 + fi * 30, 200)).save(os.path.join(src, theme, "Skybox%s.png" % face))


def make_root(root, newline="\r\n", indent=2):
    os.makedirs(os.path.join(root, "blender", "textures"), exist_ok=True)
    text = json.dumps(VORTEX, indent=indent, sort_keys=True) + "\n"
    index = os.path.join(root, "blender", "textures", "textures.json")
    with open(index, "wb") as f:
        f.write(text.replace("\n", newline).encode("utf-8"))
    return index


def read(path):
    with open(path, "rb") as f:
        return f.read()


def main():
    results = []

    def check(name, cond, detail=""):
        results.append(bool(cond))
        print(("PASS " if cond else "FAIL ") + name + ("" if cond else "  " + str(detail)[:600]))

    # 0) the script's theme list = Config.Sky.Themes + RaidThemes (the player's picks)
    with open(os.path.join(ROOT, "src", "shared", "Config.lua"), encoding="utf-8") as f:
        cfg = f.read()
    picked = set()
    for name in ("Themes", "RaidThemes"):
        m = re.search(r"\n\t%s = \{([^}]*)\}" % name, cfg)
        picked |= set(re.findall(r'"([a-z_]+)"', m.group(1))) if m else set()
    check("THEMES = Config.Sky.Themes + RaidThemes", sorted(M.THEMES) == sorted(picked) and len(M.THEMES) == 7, sorted(picked))

    tmp = tempfile.mkdtemp(prefix="skymanifest_")
    try:
        # 1) a CRLF, indent-2 index (the Windows checkout): 42 keys added, vortex entries untouched, CRLF + indent kept
        src = os.path.join(tmp, "src")
        root = os.path.join(tmp, "root")
        make_src(src)
        index = make_root(root)
        before = read(index)
        out = M.build(src, root)
        after = read(index)
        data = json.loads(after.decode("utf-8"))
        sky = sorted(k for k in data["keys"] if k.startswith("sky_"))
        check("42 sky keys sky_<theme>_<Face>", len(sky) == 42 and sky == sorted("sky_%s_%s" % (t, f) for t in THEMES for f in FACES), sky[:8])
        check("build returns the 42 keys it wrote", sorted(out) == sky, sorted(out)[:5])
        check("vortex entries untouched", all(data["keys"][k] == VORTEX["keys"][k] for k in VORTEX["keys"]) and data["comment"] == VORTEX["comment"])
        check("CRLF kept: every newline is CRLF", b"\r\n" in after and after.count(b"\n") == after.count(b"\r\n"), after[:80])
        check("indent 2 kept", after.splitlines()[1].startswith(b'  "') and not after.splitlines()[1].startswith(b'   '), after.splitlines()[1])
        check("the trailing newline kept", after.endswith(b"}\r\n"), after[-10:])
        check("sorted keys kept (the vortex text is unchanged around the new keys)", after.decode("utf-8").replace("\r\n", "\n") == json.dumps(data, indent=2, sort_keys=True) + "\n")
        e = data["keys"]["sky_day_vivid_Bk"]
        copied = os.path.join(root, "blender", "textures", "sky", "day_vivid", "SkyboxBk.png")
        check("the PNG is copied to blender/textures/sky/<theme>/Skybox<Face>.png", os.path.isfile(copied) and read(copied) == read(os.path.join(src, "day_vivid", "SkyboxBk.png")))
        check("png path relative to the game root", e.get("png") == "blender/textures/sky/day_vivid/SkyboxBk.png", e.get("png"))
        check("displayName NC sky <theme> <Face>", e.get("displayName") == "NC sky day_vivid Bk", e.get("displayName"))
        check("contentHash = the copied PNG's sha256", e.get("contentHash") == sha(copied), e.get("contentHash"))
        with Image.open(copied) as im:
            sig = "png %dx%d %s" % (im.size[0], im.size[1], im.mode)
        check("structureHash = build_vortex's size + mode signature", e.get("structureHash") == hashlib.sha256(sig.encode()).hexdigest()[:32], e.get("structureHash"))
        check("description + build hint", "living sky" in e.get("description", "") and "build_sky_manifest.py" in e.get("build", "") and "%s" in e.get("build", ""), e)
        check("index changed (sanity)", before != after)

        # 2) a second run changes nothing (byte-identical index, copies untouched)
        mtime = os.path.getmtime(copied)
        M.build(src, root)
        check("idempotent: a re-run leaves textures.json byte-identical", read(index) == after)
        check("idempotent: an unchanged PNG is not rewritten", os.path.getmtime(copied) == mtime)

        # 3) a re-rendered face: only its contentHash moves
        Image.new("RGB", (1024, 1024), (1, 2, 3)).save(os.path.join(src, "storm_teal", "SkyboxUp.png"))
        M.build(src, root)
        d2 = json.loads(read(index).decode("utf-8"))
        moved = sorted(k for k in d2["keys"] if d2["keys"][k] != data["keys"].get(k))
        check("a re-rendered face: only sky_storm_teal_Up changes", moved == ["sky_storm_teal_Up"], moved)

        # 4) an LF index with indent 4 stays LF / indent 4
        root4 = os.path.join(tmp, "root4")
        index4 = make_root(root4, newline="\n", indent=4)
        M.build(src, root4)
        t4 = read(index4)
        check("LF kept", b"\r\n" not in t4 and t4.endswith(b"}\n"))
        check("indent 4 kept", t4.splitlines()[1].startswith(b'    "') and not t4.splitlines()[1].startswith(b'     '), t4.splitlines()[1])

        # 5) refusals write nothing: a missing face, a 512 px face, a missing theme folder
        for name, kwargs in (("a theme with five faces", {"skip": {("frost_glacial", "Dn")}}),
                             ("a 512 px render", {"size": 512}),
                             ("a missing theme folder", {"themes": THEMES[:-1]})):
            bsrc = os.path.join(tmp, "bad_" + name.replace(" ", "_"))
            broot = os.path.join(tmp, "broot_" + name.replace(" ", "_"))
            make_src(bsrc, **kwargs)
            bindex = make_root(broot)
            b0 = read(bindex)
            try:
                M.build(bsrc, broot)
                refused = False
            except M.Refusal as r:
                refused = str(r)
            check("refuses %s (all or nothing)" % name, refused, "no refusal")
            check("%s: textures.json untouched, nothing copied" % name, read(bindex) == b0 and not os.path.isdir(os.path.join(broot, "blender", "textures", "sky")))

        # 6) --dry-run (the CLI) writes nothing and exits 0; the default source is the MAIN Nimbus folder's sky-final
        droot = os.path.join(tmp, "droot")
        dindex = make_root(droot)
        d0 = read(dindex)
        p = subprocess.run([sys.executable, os.path.join(ROOT, "blender", "sky", "build_sky_manifest.py"), "--src", src, "--root", droot, "--dry-run"],
                           capture_output=True, text=True)
        check("--dry-run: exit 0, writes nothing", p.returncode == 0 and read(dindex) == d0 and not os.path.isdir(os.path.join(droot, "blender", "textures", "sky")), p.stdout + p.stderr)
        p = subprocess.run([sys.executable, os.path.join(ROOT, "blender", "sky", "build_sky_manifest.py"), "--src", os.path.join(tmp, "nowhere"), "--root", droot],
                           capture_output=True, text=True)
        check("a missing source folder: exit 2 + a reason", p.returncode == 2 and "refused" in p.stderr, p.stdout + p.stderr)
        wt = os.path.join("C:\\", "x", "Nimbus", ".worktrees", "sky-t3", "nimbus-climb", "blender", "sky")
        check("default source = <main Nimbus>/.superpowers/sky-final (not the worktree)",
              os.path.normpath(M.default_src(wt)) == os.path.normpath(os.path.join("C:\\", "x", "Nimbus", ".superpowers", "sky-final")), M.default_src(wt))

        # 7) the uploader reads the result: a dry run of one sky key plans one Decal create, nothing sent
        p = subprocess.run([sys.executable, os.path.join(HERE, "upload_assets.py"), "--textures", "--dry-run", "--only", "sky_day_vivid_Bk", "--root", root,
                            "--base-url", "http://127.0.0.1:9"], capture_output=True, text=True, env=dict(os.environ, ROBLOX_API_KEY="", ROBLOX_CREATOR_ID=""))
        check("upload_assets --textures --dry-run --only sky_day_vivid_Bk: one Decal request, exit 0",
              p.returncode == 0 and "1 key(s)" in p.stdout and "Decal" in p.stdout and "nothing was sent" in p.stdout, p.stdout + p.stderr)
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    print("%d/%d passed" % (sum(results), len(results)))
    return 0 if all(results) else 1


if __name__ == "__main__":
    sys.exit(main())
